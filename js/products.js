let currentSlides = {};

function changeSlideFromProducts(productId, direction) {
  const product = products.find(p => p.id === productId);
  if (!product || !product.images) return;

  const currentIndex = currentSlides[productId] || 0;
  const imagesCount = Array.isArray(product.images) ? product.images.length : 1;
  const newIndex = (currentIndex + direction + imagesCount) % imagesCount;

  goToSlideFromProducts(productId, newIndex);
}

function goToSlideFromProducts(productId, index) {
  const product = products.find(p => p.id === productId);
  if (!product || !product.images) return;

  currentSlides[productId] = index;

  const slider = document.getElementById(`slider-${productId}`);
  if (!slider) return;

  const slides = slider.querySelectorAll('.slider-slide');
  const dots = slider.parentElement?.querySelectorAll('.dot');

  slides.forEach((slide, i) => slide.classList.toggle('active', i === index));
  if (dots) dots.forEach((dot, i) => dot.classList.toggle('active', i === index));

  slider.style.transform = `translateX(-${index * 100}%)`;
}

