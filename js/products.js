// Рендер карточки товара с мини-слайдером
function renderProducts(category = "all") {
  const grid = document.getElementById("products-grid");
  const filtered = category === "all" ? products : products.filter(p => p.category === category);

  grid.innerHTML = filtered
    .map(product => {
      const images = Array.isArray(product.images) ? product.images : [];
      const slides = images
        .map((src, i) => `<div class="slider-slide${i === 0 ? " active" : ""}">
          <img src="${src}" alt="${product.title} ${i + 1}">
        </div>`).join("");
      const dots = images
        .map((_, i) => `<span class="dot${i === 0 ? " active" : ""}" onclick="goToSlide(${product.id},${i})"></span>`).join("");
      return `
        <div class="product-card glass-card" data-category="${product.category}">
          <div class="product-slider">
            <div class="slider-container" id="slider-${product.id}">
              ${slides}
            </div>
            <div class="slider-nav">
              <button class="slider-btn prev" onclick="changeSlide(${product.id},-1)">‹</button>
              <div class="slider-dots">${dots}</div>
              <button class="slider-btn next" onclick="changeSlide(${product.id},1)">›</button>
            </div>
          </div>
          <div class="product-info">
            <h3>${product.title}</h3>
            <p class="product-description">${product.description}</p>
            <div class="product-price">${product.price}</div>
            <div class="product-features">${product.features.map(f => `<div class="feature-item">${f}</div>`).join("")}</div>
            <a href="${product.link}" target="_blank" class="product-link">Купить на Ozon</a>
          </div>
        </div>`;
    }).join("");
  animateCards(".product-card");
}

