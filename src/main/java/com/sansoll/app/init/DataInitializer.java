    // Обновленный метод saveProduct с новыми параметрами
    private void saveProduct(String title, String desc, String price, Category cat, Partner part,
            List<String> features, List<String> images, String comp, String indic,
            String dosage, String contra, String cert, String manuf, String dosageForm, String defaultDosage,
            int packSize, String unit) {
        Product p = new Product();
        p.setTitle(title);
        p.setDescription(desc);
        p.setPrice(new BigDecimal(price));
        p.setCategory(cat);
        p.setPartner(part);
        p.setFeatures(features);
        p.setComposition(comp);
        p.setIndications(indic);
        p.setDosage(dosage);
        p.setContraindications(contra);
        p.setCertificate(cert);
        p.setManufacturer(manuf);
        p.setDosageForm(dosageForm);
        p.setDefaultDosage(defaultDosage);
        p.setIsActive(true);
        p.setStock(100);
        p.setDiscount(BigDecimal.ZERO);
        p.setPackSize(packSize);
        p.setUnit(unit);

        for (String url : images) {
            ProductImage img = new ProductImage();
            img.setImageUrl(url);
            img.setProduct(p);
            p.getImages().add(img);
        }
        productRepository.save(p);
    }
